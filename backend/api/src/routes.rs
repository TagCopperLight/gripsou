//! The API's routes as data: one entry per method and path, from which the
//! router is built. The same entries list every route the server answers
//! (`frontend/src/api/routes.ts`), which the review mock is checked against.

use axum::Router;
use axum::handler::Handler;
use axum::http::Method;
use axum::routing::{MethodRouter, delete, get, patch, post, put};

use crate::AppState;

#[derive(Default)]
pub(crate) struct Routes(Vec<(Method, &'static str, MethodRouter<AppState>)>);

macro_rules! methods {
    ($($name:ident => $method:ident),* $(,)?) => {$(
        pub(crate) fn $name<H, T>(self, path: &'static str, handler: H) -> Self
        where
            H: Handler<T, AppState>,
            T: 'static,
        {
            self.with(Method::$method, path, $name(handler))
        }
    )*};
}

impl Routes {
    methods!(get => GET, post => POST, put => PUT, patch => PATCH, delete => DELETE);

    /// A route whose method router needs more than its handler (a layer);
    /// `method` must be the one it answers.
    pub(crate) fn with(
        mut self,
        method: Method,
        path: &'static str,
        route: MethodRouter<AppState>,
    ) -> Self {
        self.0.push((method, path, route));
        self
    }

    pub(crate) fn merge(mut self, other: Routes) -> Self {
        self.0.extend(other.0);
        self
    }

    pub(crate) fn list(&self) -> impl Iterator<Item = (&Method, &'static str)> {
        self.0.iter().map(|(method, path, _)| (method, *path))
    }

    pub(crate) fn into_router(self) -> Router<AppState> {
        self.0
            .into_iter()
            .fold(Router::new(), |router, (_, path, route)| {
                router.route(path, route)
            })
    }
}

/// Where the generated list lives.
pub const PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../frontend/src/api/routes.ts"
);

/// Every route under `/api`, as the TypeScript list `METHOD /path/:param`,
/// sorted by path so the file is stable.
pub fn render() -> String {
    let mut routes: Vec<(String, String)> = crate::api_routes()
        .list()
        .map(|(method, path)| {
            let path = path
                .split('/')
                .map(
                    |seg| match seg.strip_prefix('{').and_then(|s| s.strip_suffix('}')) {
                        Some(param) => format!(":{param}"),
                        None => seg.to_string(),
                    },
                )
                .collect::<Vec<_>>()
                .join("/");
            (path, method.to_string())
        })
        .collect();
    routes.sort();
    let mut out = format!(
        "// Generated by `{}` (backend/api/src/routes.rs). Do not edit.\n\n\
         /** Every route the server answers under /api. */\n\
         export const ROUTES = [\n",
        crate::wire_ts::COMMAND
    );
    for (path, method) in routes {
        out.push_str(&format!("  \"{method} {path}\",\n"));
    }
    out.push_str("] as const;\n\nexport type Route = (typeof ROUTES)[number];\n");
    out
}
