//! The TypeScript description of the API's JSON: every type a handler sends
//! or accepts, derived by ts-rs from the serde attributes, and the limits and
//! defaults the frontend must agree with. `frontend/src/api/wire.ts` holds
//! the output; `ci.sh` regenerates it and fails when the checked-in file
//! differs.

use std::any::TypeId;
use std::collections::BTreeMap;
use std::fmt::Write;

use ts_rs::{Config, TS, TypeVisitor};

use crate::{auth, budget, wire};
use gripsou_core::repo::prefs;

/// The command that writes the file, named in its header.
pub const COMMAND: &str = "cargo run -p gripsou-api --example wire-types";

/// Where the file lives.
pub const PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../frontend/src/api/wire.ts"
);

/// How ts-rs writes the types: i64 counts and timestamps fit a JS number.
pub(crate) fn config() -> Config {
    Config::new().with_large_int("number")
}

pub fn render() -> String {
    let mut types = Types {
        cfg: config(),
        decls: BTreeMap::new(),
    };
    types.roots();

    let mut out =
        format!("// Generated by `{COMMAND}` (backend/api/src/wire_ts.rs). Do not edit.\n");
    for (_, decl) in types.decls.values() {
        out.push('\n');
        out.push_str(decl);
        out.push('\n');
    }
    out.push('\n');
    out.push_str(&constants());
    out
}

pub(crate) struct Types {
    cfg: Config,
    /// By TypeScript name, so the file's order is stable.
    decls: BTreeMap<String, (TypeId, String)>,
}

impl Types {
    /// Every route's body and answer, and the query parameters the frontend
    /// builds.
    fn roots(&mut self) {
        crate::api_routes().visit_types(self);
        self.visit::<budget::dto::SummaryParams>();
        self.visit::<budget::dto::TrendParams>();
        self.visit::<wire::Range>();
    }
}

impl TypeVisitor for Types {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Primitives and wrappers have no file, hence no declaration, but a
        // wrapper's parameters may (`Vec<Account>`).
        if T::output_path().is_none() {
            T::visit_generics(self);
            return;
        }
        let name = T::ident(&self.cfg);
        let id = TypeId::of::<T>();
        if let Some((seen, _)) = self.decls.get(&name) {
            assert!(
                *seen == id,
                "two wire types are named {name}: rename one with #[ts(rename)]"
            );
            return;
        }
        let decl = format!(
            "{}export {}",
            T::docs().unwrap_or_default(),
            T::decl(&self.cfg)
        );
        self.decls.insert(name, (id, decl));
        T::visit_dependencies(self);
    }
}

/// The server's limits and defaults, as constants of the same names.
fn constants() -> String {
    let ranges: Vec<String> = wire::Range::ALL
        .iter()
        .map(|r| serde_json::to_string(r).expect("a range serializes"))
        .collect();
    let prefs =
        serde_json::to_string_pretty(&prefs::UserPrefs::default()).expect("preferences serialize");
    let mut out = String::new();
    let mut line = |name: &str, doc: &str, value: &dyn std::fmt::Display| {
        writeln!(out, "/** {doc} */\nexport const {name} = {value};")
            .expect("a String takes writes");
    };
    line(
        "PASSWORD_MIN_CHARS",
        "A new password's length bounds, in characters (code points).",
        &auth::password::MIN_CHARS,
    );
    line(
        "PASSWORD_MAX_CHARS",
        "See `PASSWORD_MIN_CHARS`.",
        &auth::password::MAX_CHARS,
    );
    line(
        "PASSKEY_NAME_MAX_CHARS",
        "The longest name a passkey may be given, in characters.",
        &auth::passkey::MAX_NAME_CHARS,
    );
    line(
        "LOT_DECIMAL_PLACES",
        "Decimal places a lot's quantity, unit price and fee may carry.",
        &gripsou_core::repo::lot::LOT_DECIMAL_PLACES,
    );
    line(
        "LOT_MAX_INTEGER_DIGITS",
        "A lot's quantity, unit price and fee are below 10^`LOT_MAX_INTEGER_DIGITS`.",
        &gripsou_core::repo::lot::LOT_MAX_INTEGER_DIGITS,
    );
    line(
        "TOTP_DIGITS",
        "The length of an authenticator code.",
        &auth::factors::TOTP_DIGITS,
    );
    line(
        "BUDGET_AI_THRESHOLD_MIN",
        "The review thresholds a user may pick, in percent.",
        prefs::BUDGET_AI_THRESHOLD_RANGE.start(),
    );
    line(
        "BUDGET_AI_THRESHOLD_MAX",
        "See `BUDGET_AI_THRESHOLD_MIN`.",
        prefs::BUDGET_AI_THRESHOLD_RANGE.end(),
    );
    line(
        "RANGES",
        "Every chart range, in the order the range selector lists them.",
        &format!(
            "[{}] as const satisfies readonly Range[]",
            ranges.join(", ")
        ),
    );
    writeln!(
        out,
        "/** What a new user's preferences read as, shown before anyone signs in. */\nexport const DEFAULT_PREFS: UserPrefs = {prefs};"
    )
    .expect("a String takes writes");
    out
}
